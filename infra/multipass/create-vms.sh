#!/usr/bin/env bash
# Creates the 3 SkyWatch VMs with Multipass and writes the Ansible inventory.
# Idempotent: existing VMs are left alone (and started if stopped).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
INVENTORY="$REPO_ROOT/infra/ansible/inventory/hosts.ini"

UBUNTU_RELEASE="${UBUNTU_RELEASE:-24.04}"
SSH_KEY="${SSH_KEY:-$HOME/.ssh/skywatch_ed25519}"

# name:cpus:memory:disk
VMS=(
  "k3s-cp:2:1536M:10G"
  "k3s-w1:2:2560M:15G"
  "k3s-w2:2:2560M:15G"
)

command -v multipass >/dev/null || { echo "multipass is not installed (brew install --cask multipass)"; exit 1; }

# Dedicated SSH key for Ansible -> VMs, injected through cloud-init.
if [[ ! -f "$SSH_KEY" ]]; then
  echo ">> generating SSH key $SSH_KEY"
  ssh-keygen -t ed25519 -N "" -C "skywatch-ansible" -f "$SSH_KEY" >/dev/null
fi

CLOUD_INIT="$(mktemp)"
trap 'rm -f "$CLOUD_INIT"' EXIT
cat >"$CLOUD_INIT" <<EOF
#cloud-config
ssh_authorized_keys:
  - $(cat "$SSH_KEY.pub")
EOF

# Prints the VM state, or nothing if the VM does not exist. `multipass info` exits non-zero for a
# missing VM; `|| true` keeps that from aborting the script under `set -e` + `pipefail`.
vm_state() { multipass info "$1" --format csv 2>/dev/null | awk -F, 'NR==2 {print $2}' || true; }

for spec in "${VMS[@]}"; do
  IFS=: read -r name cpus mem disk <<<"$spec"
  state="$(vm_state "$name")"
  if [[ -z "$state" ]]; then
    echo ">> launching $name ($cpus CPU, $mem RAM, $disk disk)"
    multipass launch "$UBUNTU_RELEASE" --name "$name" --cpus "$cpus" --memory "$mem" --disk "$disk" \
      --cloud-init "$CLOUD_INIT" --timeout 600
  elif [[ "$state" != "Running" ]]; then
    echo ">> starting $name (was $state)"
    multipass start "$name"
  else
    echo ">> $name already running"
  fi
done

ip_of() { multipass info "$1" --format csv | awk -F, 'NR==2 {print $3}'; }

mkdir -p "$(dirname "$INVENTORY")"
cat >"$INVENTORY" <<EOF
# Generated by infra/multipass/create-vms.sh - do not edit by hand.
[k3s_server]
k3s-cp ansible_host=$(ip_of k3s-cp)

[k3s_agents]
k3s-w1 ansible_host=$(ip_of k3s-w1)
k3s-w2 ansible_host=$(ip_of k3s-w2)

[k3s_cluster:children]
k3s_server
k3s_agents

[k3s_cluster:vars]
ansible_user=ubuntu
ansible_ssh_private_key_file=$SSH_KEY
# Offer only the key above. Without this, ssh also tries every key loaded in the local ssh-agent
# and the VM drops the connection with "Too many authentication failures".
ansible_ssh_common_args='-o IdentitiesOnly=yes'
EOF

echo ">> inventory written to $INVENTORY"
cat "$INVENTORY"
